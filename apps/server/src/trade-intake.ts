import { randomUUID } from "node:crypto";
import type { TradeEvent } from "../../../packages/shared/src/types.js";
import type { Store } from "./store.js";
import { normalizeTrade } from "./schemas.js";
import {
  encodedTrade,
  InboxCapacityError,
  INBOX_BATCH_SIZE,
  INBOX_MAX_BYTES,
  INTAKE_MAX_BYTES,
  INTAKE_MAX_RECORDS,
  type InboxStatus,
  type IntakeGap,
} from "./trade-inbox-store.js";

export interface IntakeState extends InboxStatus {
  memoryRecords: number;
  memoryBytes: number;
  retrying: boolean;
  admissionPaused: boolean;
  error: string | null;
}
type Dependencies = Pick<Store, "recordTrade" | "history" | "tradeInbox">;
interface Pending {
  trade: TradeEvent;
  bytes: number;
  receivedAt: number;
}

/** One bounded memory admission queue and one serial durable-inbox consumer.
 * IDs are allocated before admission and never regenerated by a retry. */
export class TradeIntake {
  private memory: Pending[] = [];
  private ids = new Set<string>();
  private bytes = 0;
  private accepting = true;
  private closed = false;
  private stopping = false;
  private timer: ReturnType<typeof setTimeout> | null = null;
  private running: Promise<void> | null = null;
  private failures = 0;
  private pendingGap: IntakeGap | null = null;
  private retained: InboxStatus = {
    pending: 0,
    pendingCapped: false,
    pendingBytes: 0,
    oldestAt: null,
    gap: null,
  };
  private statusAt = -Infinity;
  private failure: string | null = null;
  private stopTask: Promise<void> | null = null;
  constructor(
    private store: Dependencies,
    private callbacks: {
      change?: (state: IntakeState) => void;
      committed?: () => void;
      overflow?: () => void;
      capacityAvailable?: () => void;
    } = {},
    private limits = { records: INTAKE_MAX_RECORDS, bytes: INTAKE_MAX_BYTES },
  ) {}

  get canAccept() {
    return this.accepting && !this.closed;
  }
  snapshot(): IntakeState {
    return {
      ...this.retained,
      gap: this.pendingGap ?? this.retained.gap,
      memoryRecords: this.memory.length,
      memoryBytes: this.bytes,
      retrying: this.failures > 0,
      admissionPaused: !this.accepting,
      error:
        this.failure ??
        (this.retained.pending > 0 &&
        this.retained.oldestAt !== null &&
        Date.now() - this.retained.oldestAt > 30000
          ? "Retained trade observations are catching up after an ingestion delay."
          : null),
    };
  }
  start() {
    this.schedule(0);
  }
  enqueue(raw: unknown, provenance: TradeEvent["provenance"]): boolean {
    if (!this.canAccept) return false;
    // Papertrade's public:trades contract allows 1–120 observations per
    // publication. Durable appends still use their separate 50-row bound.
    const max = provenance === "public-stream" ? 120 : 50;
    if (
      !Array.isArray(raw) ||
      raw.length > max ||
      (provenance === "public-stream" && !raw.length)
    ) {
      this.gap(
        "malformed",
        null,
        "A trade publication had an unsupported batch shape.",
      );
      return false;
    }
    let malformed = 0,
      rejected = 0;
    const at = Date.now();
    for (const item of raw) {
      let trade: TradeEvent, bytes: number;
      try {
        trade = normalizeTrade(
          item,
          provenance,
          provenance === "public-stream" ? randomUUID() : undefined,
        );
        bytes = Buffer.byteLength(encodedTrade(trade));
      } catch {
        malformed++;
        continue;
      }
      // Only identical source observation IDs coalesce. Equal economic fields
      // can describe distinct real executions and must retain their multiplicity.
      if (this.ids.has(trade.id)) continue;
      if (
        this.memory.length >= this.limits.records ||
        this.bytes + bytes > this.limits.bytes
      ) {
        rejected++;
        continue;
      }
      this.memory.push({ trade, bytes, receivedAt: at });
      this.ids.add(trade.id);
      this.bytes += bytes;
    }
    if (malformed)
      this.gap(
        "malformed",
        malformed,
        "Some trade observations could not be decoded; valid neighbors were retained.",
      );
    if (rejected) {
      this.accepting = false;
      this.gap(
        "overflow",
        rejected,
        "Trade intake reached its memory bound. Live admission is paused; retained inbox work continues.",
      );
      this.callbacks.overflow?.();
    }
    this.changed();
    this.schedule(0);
    return malformed === 0 && rejected === 0;
  }
  private gap(kind: IntakeGap["kind"], count: number | null, reason: string) {
    const at = Date.now();
    this.pendingGap = {
      firstAt: Math.min(
        at,
        this.pendingGap?.firstAt ?? Infinity,
        this.retained.gap?.firstAt ?? Infinity,
      ),
      at,
      kind,
      count,
      reason,
    };
    this.changed();
    this.schedule(0);
  }
  private changed() {
    this.callbacks.change?.(this.snapshot());
  }
  private async persistGap() {
    if (!this.pendingGap) return;
    const gap = this.pendingGap;
    await this.store.tradeInbox.recordGap(gap);
    this.retained.gap = {
      ...(this.retained.gap && this.retained.gap.at > gap.at
        ? this.retained.gap
        : gap),
      firstAt: Math.min(gap.firstAt, this.retained.gap?.firstAt ?? Infinity),
    };
    if (this.pendingGap === gap) this.pendingGap = null;
    this.statusAt = -Infinity;
  }
  private schedule(delay: number) {
    if (this.closed || this.running) return;
    if (this.timer) {
      if (delay !== 0 || this.failures) return;
      clearTimeout(this.timer);
      this.timer = null;
    }
    const run = () => {
      this.timer = null;
      this.running = this.tick().finally(() => {
        this.running = null;
        if (this.closed) return;
        if (this.stopping && !this.memory.length && !this.pendingGap) {
          this.closed = true;
          return;
        }
        this.schedule(
          this.failures
            ? Math.min(15000, 1000 * 2 ** Math.min(this.failures - 1, 4))
            : this.memory.length || this.retained.pending
              ? 1
              : 1000,
        );
      });
    };
    if (delay === 0) {
      run();
      return;
    }
    this.timer = setTimeout(run, delay);
    this.timer.unref();
  }
  private async tick() {
    let capacityBlocked = false;
    try {
      // Persist already-known malformed/overflow evidence before admitting its
      // valid neighbors, so successful batch admission cannot hide that gap.
      await this.persistGap();
      if (this.closed) return;
      if (this.memory.length) {
        const batch = this.memory.slice(0, INBOX_BATCH_SIZE);
        try {
          await this.store.tradeInbox.append(
            batch.map((row) => row.trade),
            batch[0].receivedAt,
          );
          // A lost COMMIT reply leaves exactly these same objects queued for retry.
          for (const row of this.memory.splice(0, batch.length)) {
            this.bytes -= row.bytes;
            this.ids.delete(row.trade.id);
          }
        } catch (error) {
          if (!(error instanceof InboxCapacityError)) throw error;
          capacityBlocked = true;
          if (this.accepting) {
            this.accepting = false;
            this.gap(
              "overflow",
              null,
              "Durable trade inbox capacity was reached. Live admission is paused while retained work drains.",
            );
            this.callbacks.overflow?.();
          }
          // Capacity must not prevent consuming the existing durable head.
        }
        this.statusAt = -Infinity;
      }
      if (this.closed) return;
      await this.persistGap();
      if (this.closed) return;
      if (Date.now() - this.statusAt >= 5000) {
        this.retained = await this.store.tradeInbox.status();
        this.statusAt = Date.now();
      }
      if (this.closed || (this.stopping && !capacityBlocked)) return;
      const rows = await this.store.tradeInbox.head();
      for (const trade of rows.slice(0, 10)) {
        if (this.closed || (this.stopping && !capacityBlocked)) break;
        const inserted = await this.store.recordTrade(trade);
        if (this.closed) break;
        // This must also run after a duplicate (including a committed write
        // whose acknowledgement was lost), before the inbox can be removed.
        await this.store.history.ensureWallet(trade.wallet, 20);
        if (this.closed) break;
        await this.store.tradeInbox.acknowledge(trade.id);
        this.retained.pending = Math.max(0, this.retained.pending - 1);
        if (inserted) this.callbacks.committed?.();
      }
      if (!rows.length) {
        this.retained.pending = 0;
        this.retained.pendingCapped = false;
        this.retained.oldestAt = null;
      } else if (rows.length > 10)
        this.retained.pending = Math.max(1, this.retained.pending);
      this.failures = 0;
      this.failure = null;
      // Hysteresis prevents reconnecting into another full queue. Sticky gap
      // evidence survives this transport/admission recovery and every restart.
      if (
        !this.accepting &&
        !this.stopping &&
        !this.closed &&
        this.memory.length < this.limits.records / 2 &&
        this.bytes < this.limits.bytes / 2 &&
        !this.retained.pendingCapped &&
        this.retained.pending < 10000 &&
        this.retained.pendingBytes < INBOX_MAX_BYTES / 2
      ) {
        this.accepting = true;
        this.callbacks.capacityAvailable?.();
      }
    } catch {
      this.failures++;
      // Do not expose database text/parameters; every failed head stays durable.
      this.failure =
        "Trade inbox persistence or projection is delayed; pending observations are retained for retry.";
    } finally {
      this.changed();
    }
  }
  /** Stop admission immediately. At the total deadline reject to the worker's
   * fail-stop handler: it must exit without releasing ownership while any old
   * write could still be running. Durable backlog is replayed by the next owner. */
  stop(budgetMs = 40000): Promise<void> {
    if (this.stopTask) return this.stopTask;
    this.accepting = false;
    this.stopping = true;
    this.stopTask = (async () => {
      if (this.timer) clearTimeout(this.timer);
      this.timer = null;
      if (!this.memory.length && !this.pendingGap) this.closed = true;
      if (!this.closed) this.schedule(0);
      let deadline: ReturnType<typeof setTimeout> | undefined;
      try {
        await Promise.race([
          (async () => {
            while (!this.closed || this.running) {
              if (this.running) await this.running;
              else
                await new Promise<void>((resolve) => setTimeout(resolve, 10));
            }
          })(),
          new Promise<never>((_resolve, reject) => {
            deadline = setTimeout(
              () => {
                this.closed = true;
                console.error(
                  "Trade intake shutdown deadline exceeded; the worker must exit without releasing its lease.",
                );
                reject(
                  new Error(
                    "Trade intake shutdown deadline exceeded; exit without releasing the collector lease.",
                  ),
                );
              },
              Math.max(0, budgetMs),
            );
          }),
        ]);
      } finally {
        if (deadline) clearTimeout(deadline);
        if (this.timer) clearTimeout(this.timer);
        this.timer = null;
        if (this.memory.length) {
          this.gap(
            "shutdown",
            this.memory.length,
            "Shutdown ended with memory admissions not confirmed durable; source coverage may be incomplete.",
          );
          console.error(
            "Trade intake shutdown: memory admissions remain unconfirmed.",
            { count: this.memory.length },
          );
        }
        this.changed();
      }
    })();
    return this.stopTask;
  }
}
